import { describe, it, before, after } from "node:test";
import assert from "node:assert/strict";
import { promises as fs } from "fs";
import { sql } from "drizzle-orm";

process.env.DATABASE_URL = process.env.DATABASE_URL ?? "postgresql://postgres:postgres@127.0.0.1:5432/app_db";

describe("DELETE /api/analysis/:id cleanup and audit trail", () => {
  let analysisId = "";
  let fileId = "";
  let savedPath = "";
  let savedAbsPath = "";
  let db: typeof import("../src/db/index").db;
  let analyses: typeof import("../src/db/schema").analyses;
  let files: typeof import("../src/db/schema").files;
  let auditLogs: typeof import("../src/db/schema").auditLogs;
  let eq: typeof import("drizzle-orm").eq;

  before(async () => {
    const database = await import("../src/db/index");
    const schema = await import("../src/db/schema");
    const drizzle = await import("drizzle-orm");
    const storage = await import("../src/lib/server/storage");
    db = database.db;
    analyses = schema.analyses;
    files = schema.files;
    auditLogs = schema.auditLogs;
    eq = drizzle.eq;

    const [analysis] = await db.insert(analyses).values({
      uploadId: null,
      name: "delete-cleanup-test",
      mode: "local",
      options: {},
      status: "completed",
      progress: 100,
      statusText: "Completed (test)",
      completedAt: new Date(),
    }).returning();
    analysisId = analysis.id;

    const stored = await storage.saveBytes("exports", `delete-test-${analysisId}`, "temporary.txt", new TextEncoder().encode("temporary"));
    savedPath = stored.relPath;
    savedAbsPath = stored.absPath;
    const [file] = await db.insert(files).values({
      jobId: null,
      analysisId,
      uploadId: null,
      kind: "export",
      name: "temporary.txt",
      size: 9,
      mime: "text/plain",
      path: savedPath,
    }).returning();
    fileId = file.id;
    await db.insert(auditLogs).values({ analysisId, action: "test.before-delete", detail: { marker: true } });
  });

  after(async () => {
    if (!db) return;
    if (fileId) await db.delete(files).where(eq(files.id, fileId));
    if (analysisId) {
      await db.delete(auditLogs).where(sql`${auditLogs.detail}->>'deletedAnalysisId' = ${analysisId}`);
      await db.delete(auditLogs).where(eq(auditLogs.analysisId, analysisId));
      await db.delete(analyses).where(eq(analyses.id, analysisId));
    }
    if (savedAbsPath) await fs.rm(savedAbsPath, { force: true });
  });

  it("deletes generated bytes and rows while preserving detached audit history", async () => {
    const route = await import("../src/app/api/analysis/[id]/route");
    const response = await route.DELETE(
      new Request(`http://localhost/api/analysis/${analysisId}`, { method: "DELETE" }) as never,
      { params: Promise.resolve({ id: analysisId }) }
    );
    assert.equal(response.status, 200);
    assert.deepEqual(await response.json(), { status: "deleted" });

    const [remainingFile] = await db.select().from(files).where(eq(files.id, fileId)).limit(1);
    assert.equal(remainingFile, undefined);
    await assert.rejects(() => fs.access(savedAbsPath));

    const detached = await db.select().from(auditLogs)
      .where(sql`${auditLogs.detail}->>'deletedAnalysisId' = ${analysisId}`);
    assert.ok(detached.some((entry) => entry.action === "test.before-delete" && entry.analysisId === null));
    assert.ok(detached.some((entry) => entry.action === "analysis.deleted" && entry.analysisId === null));
  });
});
